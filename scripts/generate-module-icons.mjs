function run() {
    const iconNames = new Set(['Box']);
    Object.values(ICON_MAP).forEach((name) => iconNames.add(name));
    const importItems = Array.from(iconNames).map((name) => name === 'Infinity' ? 'Infinity as InfinityIcon' : name).sort();

    const entries = Object.entries(ICON_MAP).map(([id, iconName]) => {
        const componentName = iconName === 'Infinity' ? 'InfinityIcon' : iconName;
        return `    '${id}': ${componentName},`;
    }).join('\n');

    const fileContent = `// Centralized module icon registry mapping every module across 15 domains to Lucide icons.
import {
    ${importItems.join(', ')}
} from 'lucide-react';

export const MODULE_ICONS = {
${entries}
};

export function getModuleIcon(moduleId) {
    return MODULE_ICONS[moduleId] || Box;
}
`;

    writeFileSync(targetFile, fileContent, 'utf8');
    console.log(`Generated ${targetFile} with ${Object.keys(ICON_MAP).length} module icon mappings.`);
}

run();
